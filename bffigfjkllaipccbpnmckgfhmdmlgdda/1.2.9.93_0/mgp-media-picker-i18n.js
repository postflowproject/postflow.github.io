/** The popup's language (localStorage 'mgp_lang', same extension origin), else the browser's; 'en' if not one of ours. */
function pickerLang() {
  let raw = '';
  try { raw = localStorage.getItem('mgp_lang') || ''; } catch (_) {}
  if (!raw) { try { raw = navigator.language || ''; } catch (_) {} }
  const code = String(raw).toLowerCase().split(/[-_]/)[0];
  return Object.prototype.hasOwnProperty.call(PICKER_I18N, code) ? code : 'en';
}

/** The text for `key` in `lang` (default: the user's), with {{name}} filled from `vars`; English when a language lacks it. */
function tr(key, vars, lang) {
  const L = lang || pickerLang();
  const pick = (dict) => {
    let v = dict && dict[key];
    if (v && typeof v === 'object') {
      let cat = 'other';
      try { cat = new Intl.PluralRules(L).select(Number(vars && vars.count) || 0); } catch (_) {}
      v = v[cat] != null ? v[cat] : v.other;
    }
    return typeof v === 'string' ? v : null;
  };
  const s = pick(PICKER_I18N[L]) ?? pick(PICKER_I18N.en) ?? key;
  return s.replace(/\{\{(\w+)\}\}/g, (m, k) => (vars && vars[k] != null ? String(vars[k]) : m));
}
